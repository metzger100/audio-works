RECORD_NAMES = {
    "results.json",
    "optimization.json",
    "verification.json",
    "failure.json",
    "checkpoint.json",
    "provenance_correction.json",
}


def navigation_output(path):
    return (
        path.endswith("/INDEX.md")
        or path
        in {
            "CURRENT.md",
            "docs/evidence.md",
            "docs/evidence-index.json",
            "docs/current-evidence.md",
            "docs/history.md",
            "meridian-microphone/lab/research/memory/experiment-log.md",
        }
        or "/index-pages/" in path
        or path.startswith("docs/evidence-index-parts/")
        or path.startswith("docs/data-pages/evidence-index-")
        or path.startswith("docs/evidence/")
        or path.startswith("docs/history-pages/")
        or (path == "meridian-microphone/lab/research/prompts/prompt-pack.md")
    )


def record_index(view):
    rows = []
    for path in sorted(view.paths):
        match = re.fullmatch(
            "meridian(?:-microphone)?/lab/results/(runs|device_models|verification)/([^/]+)/([^/]+\\.json)",
            path,
        )
        if not match or match[3] not in RECORD_NAMES:
            continue
        value = parse(view.text(path), ".json")
        manifest = value.get("source_manifest")
        import hashlib

        rows.append(
            {
                "path": path,
                "kind": match[1],
                "record_type": match[3],
                "experiment_id": value.get("experiment_id", match[2]),
                **{
                    key: value.get(key)
                    for key in (
                        "timestamp_utc",
                        "status",
                        "eligible",
                        "eligible_for_production",
                        "candidate_id",
                        "parent_experiments",
                        "parent_candidates",
                        "spec_sha256",
                        "suite_sha256",
                        "source_unchanged",
                    )
                },
                "source_manifest_sha256": hashlib.sha256(canonical(manifest)).hexdigest()
                if manifest
                else None,
            }
        )
    return {
        "schema_version": 1,
        "note": "Original statuses retained; null means unavailable legacy metadata, not pass.",
        "records": rows,
    }


def pages(outputs, destination, title, introduction, entries):
    header = f"<!-- Generated by tools/project.py refresh. -->\n# {title}\n\n{introduction}\n\n"
    groups = []
    current = []
    for entry in entries:
        if current and len(header + "\n".join(current + [entry])) > 12000:
            groups.append(current)
            current = []
        current.append(entry)
    groups.append(current)
    if len(groups) == 1:
        outputs[destination] = (header + "\n".join(current) + "\n").encode()
        return
    directory = posixpath.dirname(destination) + "/index-pages"
    namespace = PurePosixPath(destination).stem.lower()
    pointers = []
    for index, group in enumerate(groups):
        path = f"{directory}/{namespace}-{index + 1:04d}.md"

        def rebase(match, path=path):
            from urllib.parse import urlsplit

            target = match[1]
            if urlsplit(target).scheme or target.startswith(("#", "//")):
                return match[0]
            return (
                "]("
                + posixpath.relpath(
                    posixpath.normpath(posixpath.join(posixpath.dirname(destination), target)),
                    posixpath.dirname(path),
                )
                + ")"
            )

        body = re.sub("\\]\\(([^)]+)\\)", rebase, "\n".join(group))
        rebased_header = re.sub("\\]\\(([^)]+)\\)", rebase, header)
        outputs[path] = (rebased_header + body + "\n").encode()
        pointers.append(f"- [Page {index + 1}]({link(path, destination)})")
    outputs[destination] = (header + "\n".join(pointers) + "\n").encode()


def render_current(outputs, register):
    """Render the registered current facts and their evidence links."""
    current = [
        "<!-- Generated by tools/project.py refresh; edit project.json. -->",
        "# Current project state",
        "",
        f"As of {register['as_of']}: **{register['phase']}**.",
        "",
    ]
    current.extend(
        (
            f"- **{category.capitalize()}:** {state}"
            for category, state in register["readiness"].items()
        )
    )
    current.extend(
        [
            "",
            "**Blockers:** " + " ".join(register["blockers"]),
            "",
            "**Next:** " + register["next_action"],
            "",
            "Evidence:",
            "",
        ]
    )
    current.append("[Supporting records](docs/current-evidence.md)")
    current.extend(["", "[Navigation](docs/INDEX.md) · [Quality contract](QUALITY.md)", ""])
    outputs["CURRENT.md"] = "\n".join(current).encode()
    pages(
        outputs,
        "docs/current-evidence.md",
        "Current supporting records",
        "Authoritative pointers from project.json; read relevant originals and conditions.",
        [
            f"- [{PurePosixPath(path).name}]({link(path, 'docs/current-evidence.md')})"
            for path in register["evidence"]
        ],
    )


def navigation_files(view, register):
    """Select maintained sources and their parent hubs without traversing originals."""
    from .structure import original

    summaries = {
        "CURRENT.md",
        "docs/current-evidence.md",
        "docs/history.md",
        "meridian-microphone/lab/research/memory/experiment-log.md",
        "meridian-microphone/lab/research/prompts/prompt-pack.md",
    }
    files = {
        p
        for p in view.paths
        if (not navigation_output(p) or p in summaries) and (not original(p, register))
    }
    files.update(summaries)
    files.update(register.get("external_files", {}))
    directories = set()
    for path in files:
        parent = PurePosixPath(path).parent
        while str(parent) != ".":
            directories.add(str(parent))
            parent = parent.parent
    directories.update((module["prefix"].rstrip("/") for module in register["modules"]))
    for directory in list(directories):
        parent = PurePosixPath(directory).parent
        while str(parent) != ".":
            directories.add(str(parent))
            parent = parent.parent
    return (files, directories)


def render_modules(outputs, files, directories, register):
    """Expose immediate files and child hubs for each maintained folder."""
    for directory in sorted(directories):
        destination = directory + "/INDEX.md"
        if any(
            (
                directory == prefix.rstrip("/") or directory.startswith(prefix)
                for prefix in register.get("immutable_prefixes", [])
            )
        ):
            continue
        title = next(
            (
                module["name"]
                for module in register["modules"]
                if module["prefix"].rstrip("/") == directory
            ),
            directory,
        )
        purpose = next(
            (
                module["purpose"]
                for module in register["modules"]
                if module["prefix"].rstrip("/") == directory
            ),
            "Immediate contents and child hubs.",
        )
        entries = [
            f"- [{PurePosixPath(p).name}]({link(p, destination)}) — {classify(p, register)}"
            for p in sorted(files)
            if str(PurePosixPath(p).parent) == directory
        ]
        entries += [
            f"- [{PurePosixPath(child).name}/]({link(child + '/INDEX.md', destination)})"
            for child in sorted(directories)
            if str(PurePosixPath(child).parent) == directory
            and (not child.startswith(tuple(register.get("immutable_prefixes", []))))
        ]
        pages(outputs, destination, str(title), purpose, entries)


