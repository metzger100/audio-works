def render_evidence(outputs, view, register):
    """Index original history and experiment records without changing their bytes."""
    pages(
        outputs,
        "docs/history.md",
        "Preserved research and policy history",
        "Original bytes retain SHA256 and baseline Git provenance. Historical embedded links describe their original layout; use current subject hubs for live material.",
        [
            f"- [{declaration['original_path']}]({link(path, 'docs/history.md')}) — `{declaration['sha256']}`"
            for path, declaration in sorted(register.get("original_files", {}).items())
        ],
    )
    log = "meridian-microphone/lab/research/memory/experiment-log.md"
    index = record_index(view)
    pages(
        outputs,
        log,
        "Experiment memory",
        "[All original records](../../../../docs/evidence.md) · [Original narrative](../../../../docs/history/2026-10-09/meridian-microphone/lab/research/experiment_log.md). Statuses and ancestry remain authoritative in original records. Latest twenty records:",
        [
            f"- [{row['experiment_id']}]({link(row['path'], log)}) — {(row['status'] if row['status'] is not None else 'unknown')}; candidate {row['candidate_id']}; parents {row['parent_experiments']}"
            for row in index["records"][-20:]
        ],
    )
    outputs.update(bounded_data(index, "docs/evidence-index.json"))
    groups = {
        "device_models": "Device model controls",
        "runs": "Qualification and optimization attempts",
        "verification": "Verification batches",
    }
    hub_entries = []
    for kind, title in groups.items():
        destination = "docs/evidence/" + kind.replace("_", "-") + ".md"
        rows = [row for row in index["records"] if row["kind"] == kind]
        entries = [
            f"- [{row['experiment_id']} / {row['record_type']}]({link(row['path'], destination)}) — {(row['status'] if row['status'] is not None else 'unknown')}"
            + (
                "; source changed — no completion credit"
                if row["source_unchanged"] is False
                else ""
            )
            for row in rows
        ]
        pages(
            outputs,
            destination,
            title,
            "Original conditions, statuses, failures and parents remain authoritative. [Structured index](../evidence-index.json).",
            entries,
        )
        hub_entries.append(
            f"- [{title}]({link(destination, 'docs/evidence.md')}) — {len(rows)} records"
        )
    pages(
        outputs,
        "docs/evidence.md",
        "Original experiment evidence",
        "[Structured index](evidence-index.json). Select a subject hub; a repository pass establishes no hardware qualification.",
        hub_entries,
    )


def render_prompts(outputs, files):
    """Link individual task prompts to their shared entry hub."""
    prompts = sorted(
        (
            p
            for p in files
            if re.fullmatch("meridian-microphone/lab/research/prompts/\\d\\d[-_].*\\.md", p)
        )
    )
    pack = "meridian-microphone/lab/research/prompts/prompt-pack.md"
    pages(
        outputs,
        pack,
        "Research task hub",
        "Individual prompts and the shared workflow are authoritative. Check current progress before executing a task.",
        [f"- [{PurePosixPath(p).stem}]({link(p, pack)})" for p in prompts],
    )


def render(view, register):
    outputs = {}
    render_current(outputs, register)
    files, directories = navigation_files(view, register)
    render_modules(outputs, files, directories, register)
    render_root(outputs, files, directories)
    render_evidence(outputs, view, register)
    render_prompts(outputs, files)
    return outputs
